@client.event
async def on_ready():
    await tree.sync()
    print(f"⚡ Commands synced (global)")
    if guild_obj:
        await tree.sync(guild=guild_obj)
        print(f"⚡ Commands synced to guild {GUILD_ID}")

    # Load GitHub keywords on startup
    await load_github_keywords()

    # Reload every 30 minutes
    async def refresh_loop():
        while True:
            await asyncio.sleep(30 * 60)
            await load_github_keywords()

    client.loop.create_task(refresh_loop())


@client.event
async def on_message(message: discord.Message):
    if message.author == client.user:
        return
    if message.channel.id != TARGET_CHANNEL_ID:
        return

    content = message.content.strip()
    if not content:
        return

    power = extract_power(content)
    question = build_question(power)
    await message.reply(question, mention_author=False)

